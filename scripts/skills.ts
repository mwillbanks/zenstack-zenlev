import assert from 'node:assert/strict'
import { lstat, mkdir, mkdtemp, readdir, rename, rm } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'

export const skillDirectory = 'website/content/docs/guides/_skills'
export const reviewPath = 'skills-review.json'
const marker = '.npmignore'
const generated = '# Generated by Zenlev skills:prepare. Edit the documentation sources.\n'
const frontmatter = /^---\n([\s\S]+?)\n---\n/
const skillName = /^[a-z0-9]+(?:-[a-z0-9]+)*$/

type Review = { reason: string; files: Record<string, string> }
type Reviews = Record<string, Review>
type Skill = { name: string; source: string; manifest: string; files: string[] }

async function loadSkills(root: string): Promise<Skill[]> {
  const directory = join(root, skillDirectory)
  const entries = (await readdir(directory, { withFileTypes: true })).sort((a, b) =>
    a.name.localeCompare(b.name, 'en'),
  )
  assert(entries.length > 0, 'No canonical skills found')

  return Promise.all(
    entries.map(async (entry) => {
      assert(
        entry.isDirectory() && skillName.test(entry.name),
        'Invalid skill directory: ' + entry.name,
      )
      const file = `${skillDirectory}/${entry.name}/SKILL.md`
      const source = await read(root, file)
      const manifest = frontmatter.exec(source)?.[1]
      assert(manifest, file + ' needs YAML frontmatter')
      const data = Bun.YAML.parse(manifest) as {
        name?: unknown
        metadata?: { library?: unknown; library_version?: unknown }
        sources?: unknown
      }
      assert(data?.name === entry.name, file + ' must match its directory name')
      assert(
        data.metadata?.library === '@mwillbanks/zenstack-zenlev',
        file + ' must name the package',
      )
      assert(
        data.metadata.library_version === undefined,
        file + ' must let staging set the version',
      )
      assert(/^metadata:\n/m.test(manifest), file + ' must use block metadata')
      const files = data.sources
      assert(
        Array.isArray(files) &&
          files.length > 0 &&
          files.every((value) => typeof value === 'string'),
        file + ' needs a sources list',
      )
      assert(
        new Set(files).size === files.length && !files.includes(file),
        file + ' lists duplicate sources',
      )
      return { name: entry.name, source, manifest, files: [file, ...files].sort() }
    }),
  )
}

async function read(root: string, file: string): Promise<string> {
  const parts = file.split('/')
  assert(
    parts.every((part) => part && part !== '.' && part !== '..' && !part.includes('\\')),
    'Expected repository-relative path: ' + file,
  )
  let absolute = root
  for (const part of parts) {
    absolute = join(absolute, part)
    const info = await lstat(absolute).catch((error: NodeJS.ErrnoException) => {
      if (error.code === 'ENOENT')
        throw new Error('Missing skill source: ' + file, { cause: error })
      throw error
    })
    assert(!info.isSymbolicLink(), 'Skill paths must not cross symlinks: ' + file)
  }
  assert(relative(root, absolute) === join(...parts), 'Invalid skill path: ' + file)
  return (await Bun.file(absolute).text()).replaceAll('\r\n', '\n')
}

async function fingerprints(root: string, files: string[]): Promise<Record<string, string>> {
  const results = await Promise.all(
    files.map(async (file) => [
      file,
      new Bun.CryptoHasher('sha256').update(await read(root, file)).digest('hex'),
    ]),
  )
  return Object.fromEntries(results)
}

async function readReviews(root: string): Promise<Reviews> {
  const file = Bun.file(join(root, reviewPath))
  return (await file.exists()) ? ((await file.json()) as Reviews) : {}
}

export async function recordReview(root: string, name: string, reason: string): Promise<Reviews> {
  assert(reason.trim(), 'Provide a concrete explanation of the evidence reviewed')
  const skill = (await loadSkills(root)).find((entry) => entry.name === name)
  assert(skill, 'Unknown skill: ' + name)
  const reviews = await readReviews(root)
  reviews[name] = { reason: reason.trim(), files: await fingerprints(root, skill.files) }
  return Object.fromEntries(Object.entries(reviews).sort(([a], [b]) => a.localeCompare(b, 'en')))
}

export async function prepareSkills(root: string): Promise<void> {
  const skills = await loadSkills(root)
  const reviews = await readReviews(root)
  const byName = new Set(skills.map(({ name }) => name))
  const failures = Object.keys(reviews)
    .filter((name) => !byName.has(name))
    .map((name) => 'Remove the obsolete review for ' + name)
  for (const skill of skills) {
    const review = reviews[skill.name]
    const actual = await fingerprints(root, skill.files).catch((error: unknown) => {
      if (error instanceof Error)
        throw new Error(skill.name + ': ' + error.message, { cause: error })
      throw error
    })
    if (!review?.reason?.trim() || !review.files) {
      failures.push(skill.name + ': no recorded review')
      continue
    }
    const changed = new Set([...Object.keys(review.files), ...Object.keys(actual)])
    for (const file of changed) {
      if (review.files[file] !== actual[file]) failures.push(skill.name + ': review ' + file)
    }
  }
  assert(failures.length === 0, 'Skill review required:\n' + failures.join('\n'))

  const { version } = (await Bun.file(join(root, 'package.json')).json()) as { version?: unknown }
  assert(typeof version === 'string' && version.length > 0, 'Package needs a version')
  const output = join(root, 'skills')
  const existing = await lstat(output).catch((error: NodeJS.ErrnoException) => {
    if (error.code !== 'ENOENT') throw error
  })
  if (existing) {
    assert(
      existing.isDirectory() && (await Bun.file(join(output, marker)).text()) === generated,
      'The root skills directory must be owned by the Zenlev generator',
    )
  }

  const temporary = await mkdtemp(join(root, '.zenlev-skills-'))
  try {
    await Bun.write(join(temporary, marker), generated)
    for (const skill of skills) {
      const target = join(temporary, skill.name, 'SKILL.md')
      await mkdir(dirname(target))
      const manifest = skill.manifest.replace(
        /^metadata:\n/m,
        `metadata:\n  library_version: ${JSON.stringify(version)}\n`,
      )
      await Bun.write(
        target,
        skill.source.replace(frontmatter, () => `---\n${manifest}\n---\n`),
      )
    }
    if (existing) await rm(output, { recursive: true })
    await rename(temporary, output)
  } finally {
    await rm(temporary, { recursive: true, force: true })
  }
}

if (import.meta.main) {
  const root = resolve(import.meta.dir, '..')
  const [command, name, reason] = Bun.argv.slice(2)
  if (command === 'review') {
    assert(name && reason, 'Usage: bun run skills:review <name> <reason>')
    console.log(JSON.stringify(await recordReview(root, name, reason), null, 2))
  } else {
    assert(command === undefined, 'Unknown skills command: ' + command)
    await prepareSkills(root)
  }
}
